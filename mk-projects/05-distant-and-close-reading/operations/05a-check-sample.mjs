// Step 5a (deterministic code): draw a reproducible random sample of passages for a human to judge,
// WITHOUT showing the model's answers, so the reader isn't nudged. 15 passages the model called
// scenes of instruction and 15 it did not (a stratified sample: a purely random 30 would contain
// only a handful of positives). Writes:
//   operations/05-check-sheet.md         the passages to read, blind
//   operations/05-check-judgments.json   a blank form to fill in (true / false and a note per passage),
//                                        created only if it doesn't exist yet, so judgments are never overwritten
import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { OPS, readJSON, writeJSON, seeded } from './_lib.mjs';

const SEED = 20261103, PER_STRATUM = 15;
const { texts, chunks } = readJSON('01-chunks.json');
const { results } = readJSON('03-classifications.json');
const title = Object.fromEntries(texts.map((t) => [t.id, t.title]));
const rand = seeded(SEED);
const shuffle = (a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };

const usable = chunks.filter((c) => results[c.id] && c.words >= 40);
const pos = usable.filter((c) => results[c.id].is_instance && results[c.id].strength > 0);
const neg = usable.filter((c) => !(results[c.id].is_instance && results[c.id].strength > 0));
// Mix the two strata together so the reader can't tell which is which.
const sample = shuffle([...shuffle(pos).slice(0, PER_STRATUM), ...shuffle(neg).slice(0, PER_STRATUM)]);

let md = `---\ntitle: "Step 5: blind check sheet"\ndescription: ${sample.length} passages drawn at random (seed ${SEED}) for a person to judge before looking at the model's answers. Generated by 05a-check-sample.mjs.\nauthor: claude\n---\n\n# Step 5: blind check sheet\n\nFor each passage, decide: **is this a scene of instruction?** (the definition is in \`03-classify-prompt.md\`). Record true or false, and a short note, in \`05-check-judgments.json\`, then run \`05b-check-score.mjs\`. Don't open \`03-classifications.json\` until you're done.\n\nThe sample is stratified: half the passages are ones the model called scenes of instruction, half are not, mixed together. Population sizes: ${pos.length} model positives, ${neg.length} model negatives (passages under 40 words excluded).\n`;
sample.forEach((c, i) => { md += `\n## ${i + 1}. \`${c.id}\`, ${title[c.text_id]}, ${c.section}\n\n${c.text.split('\n\n').map((p) => '> ' + p).join('\n>\n')}\n`; });
writeFileSync(join(OPS, '05-check-sheet.md'), md);
writeJSON('05-check-sample.json', { seed: SEED, population: { model_positive: pos.length, model_negative: neg.length }, ids: sample.map((c) => c.id) });
if (!existsSync(join(OPS, '05-check-judgments.json'))) {
  writeJSON('05-check-judgments.json', { judged_by: '', note: '', judgments: Object.fromEntries(sample.map((c) => [c.id, { is_instance: null, note: '' }])) });
}
console.log(`sampled ${sample.length} → operations/05-check-sheet.md`);
