// Step 4 (deterministic code): compare the keyword search (step 2) with the model (step 3).
// Also checks, in code, that every evidence quotation the model gave actually occurs in its passage.
// Writes operations/04-comparison.json (counts and lists) and operations/04-comparison.md (readable, with examples).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { OPS, readJSON, writeJSON } from './_lib.mjs';

const { texts, chunks } = readJSON('01-chunks.json');
const { hits } = readJSON('02-keyword-hits.json');
const { model, results } = readJSON('03-classifications.json');

// Normalize curly quotes, dashes, underscores (Gutenberg italics), and spacing before matching quotations.
const norm = (s) => s.toLowerCase().replace(/[“”"]/g, '"').replace(/[‘’']/g, "'").replace(/[—–-]+/g, '-').replace(/_/g, '').replace(/\s+/g, ' ').trim();
// Ignore quotation marks, ellipses, and punctuation at the ends of the model's quotation; everything inside must match.
const verify = (quote, text) => !quote || norm(text).includes(norm(quote).replace(/^[\s"'.,;:…]+|[\s"'.,;:…]+$/g, '').trim());

const rows = chunks.map((c) => {
  const r = results[c.id];
  return { id: c.id, text_id: c.text_id, section: c.section, keyword: !!hits[c.id], words: hits[c.id] || [], model: !!(r && r.is_instance && r.strength > 0), strength: r ? r.strength : null, evidence_ok: r ? verify(r.evidence, c.text) : null };
});

const tally = (list) => ({
  passages: list.length,
  keyword: list.filter((r) => r.keyword).length,
  model: list.filter((r) => r.model).length,
  model_strong: list.filter((r) => r.strength >= 2).length,
  both: list.filter((r) => r.keyword && r.model).length,
  keyword_only: list.filter((r) => r.keyword && r.strength !== null && !r.model).length,
  model_only: list.filter((r) => !r.keyword && r.model).length,
  model_only_strong: list.filter((r) => !r.keyword && r.strength >= 2).length,
  unclassified: list.filter((r) => r.strength === null).length,
});
const summary = { all: tally(rows) };
for (const t of texts) summary[t.id] = tally(rows.filter((r) => r.text_id === t.id));

const badQuotes = rows.filter((r) => r.evidence_ok === false).map((r) => r.id);
const lists = {
  both: rows.filter((r) => r.keyword && r.model).map((r) => r.id),
  keyword_only: rows.filter((r) => r.keyword && r.strength !== null && !r.model).map((r) => r.id),
  model_only: rows.filter((r) => !r.keyword && r.model).map((r) => r.id),
};
writeJSON('04-comparison.json', { model, summary, lists, evidence_not_found: badQuotes });

// A readable report with examples of each disagreement.
const byId = Object.fromEntries(chunks.map((c) => [c.id, c]));
const title = Object.fromEntries(texts.map((t) => [t.id, t.title]));
const pick = (ids, n) => {
  // Spread the examples across texts: take the strongest from each text in turn.
  const per = {};
  for (const id of ids) (per[byId[id].text_id] ||= []).push(id);
  for (const k in per) per[k].sort((a, b) => (results[b]?.strength ?? 0) - (results[a]?.strength ?? 0));
  const out = [];
  while (out.length < n && Object.values(per).some((l) => l.length)) for (const k in per) if (per[k].length && out.length < n) out.push(per[k].shift());
  return out;
};
const excerpt = (s, n = 60) => { const w = s.replace(/\s+/g, ' ').split(' '); return w.slice(0, n).join(' ') + (w.length > n ? ' …' : ''); };

let md = `---\ntitle: "Step 4: keyword search vs. model reading"\ndescription: Where the keyword search and the model's classification agree and disagree, with examples. Generated by 04-compare.mjs; do not edit by hand.\nauthor: claude\n---\n\n# Step 4: keyword search vs. model reading\n\nModel: \`${model}\`. A passage counts as a model hit when the model says it is a scene of instruction (strength 1 to 3); "strong" means strength 2 or 3.\n\n| text | passages | keyword hits | model hits (strong) | both | keyword only | model only (strong) |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n`;
for (const k of [...texts.map((t) => t.id), 'all']) {
  const s = summary[k];
  md += `| ${k === 'all' ? '**all**' : title[k]} | ${s.passages} | ${s.keyword} | ${s.model} (${s.model_strong}) | ${s.both} | ${s.keyword_only} | ${s.model_only} (${s.model_only_strong}) |\n`;
}
md += `\nEvidence quotations checked against their passages in code: ${rows.filter((r) => r.evidence_ok !== null && r.model).length - badQuotes.filter((id) => rows.find((r) => r.id === id).model).length} found verbatim, ${badQuotes.length} not found${badQuotes.length ? ` (${badQuotes.join(', ')})` : ''}.\n`;
md += `\n## The model found it; no keyword did\n\nScenes of instruction that a search for teach / learn / lesson / instruct / educate / school / pupil / tutor would miss.\n`;
for (const id of pick(lists.model_only.filter((id) => results[id].strength >= 2), 8)) {
  const r = results[id];
  md += `\n### ${title[byId[id].text_id]}, ${byId[id].section} (\`${id}\`, strength ${r.strength})\n\n${r.instructor} → ${r.learner}: ${r.what_is_taught}.\n\n> ${r.evidence}\n\nModel's reason: ${r.reason}\n`;
}
md += `\n## A keyword matched; the model said no\n\nMostly "learned" meaning "found out", or teaching mentioned in passing.\n`;
for (const id of pick(lists.keyword_only, 8)) {
  const r = results[id];
  md += `\n### ${title[byId[id].text_id]}, ${byId[id].section} (\`${id}\`), keyword: ${[...new Set(hits[id])].join(', ')}\n\n> ${excerpt(byId[id].text)}\n\nModel's reason: ${r.reason}\n`;
}
writeFileSync(join(OPS, '04-comparison.md'), md);
console.log(summary.all, `quotes not found: ${badQuotes.length}`);
